"""Builds deploy/suncom/01-logins.sql and 03-grants.sql: every login and grant Prime's deploy files add,
for Suncom.

Prime's grants came one migration at a time (db-logins.sql, db-grants-*.sql, the agent's
ops/db-agent-login.sql). A new installation needs them all at once, after `alembic upgrade head` on an empty
nudgeai. This reads those files, keeps every GRANT, swaps Prime's hosts and Portal database for Suncom's and
drops duplicates, so a grant added to Prime's files later can be carried over by running it again.
Run:  python deploy/suncom/build_grants.py
"""

from __future__ import annotations

import re
from pathlib import Path

API = Path(__file__).resolve().parents[2]
AGENT_SQL = API.parent / "nudgelab" / "ops" / "db-agent-login.sql"
HERE = Path(__file__).parent

WEB = "100.59.145.97"  # suncom-nudgelab-web (API + dashboard)
AGENTS = ["34.239.75.17", "54.161.141.244"]  # suncom-nudgelab-main, suncom-nudgelab-worker-1
PORTAL_DB = "suncomportal"
COMPLETIONS = "suncom_nudge_ai_completions"
PRIME_AGENTS = {
    "35.173.142.66",
    "44.221.150.77",
    "18.204.20.139",
    "34.200.118.174",
    "54.82.245.163",
    "NEW_IP",
}
SKIP_FILES = {"db-logins-fix-host.sql", "db-revoke-agent-wanaka.sql"}


def statements(path: Path) -> list[str]:
    text = "\n".join(line.split("--", 1)[0] for line in path.read_text(encoding="utf-8").splitlines())
    return [" ".join(s.split()) for s in text.split(";") if s.strip()]


def suncom(stmt: str) -> list[str]:
    stmt = stmt.replace("'10.0.1.148'", f"'{WEB}'").replace("'<API server IP>'", f"'{WEB}'")
    stmt = stmt.replace("primetwok.", f"{PORTAL_DB}.").replace("prime_nudge_ai_completions", COMPLETIONS)
    host = re.search(r"TO '[a-z_]+'@'([^']+)'", stmt)
    if host and host.group(1) in PRIME_AGENTS:
        return [stmt.replace(f"'{host.group(1)}'", f"'{ip}'") for ip in AGENTS]
    return [stmt]


def main() -> None:
    files = [API / "deploy" / "db-logins.sql", API / "deploy" / "db-grants-api-tables.sql"]
    files += sorted(p for p in (API / "deploy").glob("db-grants-0*.sql") if p.name not in SKIP_FILES)
    files.append(AGENT_SQL)
    grants: list[str] = []
    for path in files:
        for stmt in statements(path):
            if (
                not stmt.upper().startswith("GRANT")
                or re.search(r"\b(wanaka|nudge)\.", stmt)
                or "204.236.179.185" in stmt
            ):
                continue
            for s in suncom(stmt):
                if s not in grants:
                    grants.append(s)
    # The agent records each pass in Suncom's Portal (completions.py), as Prime's agent does in primetwok.
    for ip in AGENTS:
        grants.append(f"GRANT SELECT, INSERT, UPDATE ON {PORTAL_DB}.{COMPLETIONS} TO 'nudgeai_agent'@'{ip}'")

    logins = [
        ("nudgelab_api_migrate", WEB, "MIGRATE"),
        ("nudgelab_api", WEB, "API"),
        ("nudgelab_sync", WEB, "SYNC"),
        ("nudgelab_portal_ro", WEB, "PORTAL_RO"),
    ] + [("nudgeai_agent", ip, "AGENT") for ip in AGENTS]
    users = {re.search(r"TO ('[a-z_]+'@'[^']+')", g).group(1) for g in grants}
    assert users == {f"'{u}'@'{h}'" for u, h, _ in logins}, users

    head = [
        "-- Generated by deploy/suncom/build_grants.py; don't edit. Server database-1 (Suncom's RDS):",
        f"-- databases nudgeai (NudgeLab) and {PORTAL_DB} (Suncom Portal). Run as the RDS master user;",
        "-- order in deploy/suncom/README.md.",
    ]
    migrate = [g for g in grants if "'nudgelab_api_migrate'" in g]
    logins_sql = (
        head
        + [
            "-- 01: the logins, before the migrations. Replace each <..._PASSWORD> with its own strong",
            "-- password (the same AGENT password for both agent hosts). Every login must use TLS",
            "-- (REQUIRE SSL); nothing else on the server is affected. The migration login gets its grant",
            "-- now; everything else waits for the tables (03-grants.sql).",
            "",
        ]
        + [f"CREATE USER '{u}'@'{h}' IDENTIFIED BY '<{p}_PASSWORD>' REQUIRE SSL;" for u, h, p in logins]
    )
    logins_sql += [""] + [g + ";" for g in migrate]
    logins_sql += [
        "",
        "-- Check: SELECT user, host, ssl_type FROM mysql.user WHERE user LIKE 'nudge%';",
        "--        (6 rows, ssl_type ANY)",
    ]
    rest = [g for g in grants if g not in migrate]
    grants_sql = head + ["-- 03: the grants, after `alembic upgrade head` has created nudgeai's tables.", ""]
    grants_sql += [g + ";" for g in rest]
    grants_sql += ["", "-- Check: SHOW GRANTS FOR 'nudgeai_agent'@'34.239.75.17';"]
    for name, lines in (("01-logins.sql", logins_sql), ("03-grants.sql", grants_sql)):
        (HERE / name).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"01-logins.sql: {len(logins)} logins + {len(migrate)} grant; 03-grants.sql: {len(rest)} grants")


if __name__ == "__main__":
    main()
